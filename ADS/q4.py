#Let us call a two-dimensional n ×n array A a Miller array of size n if (a) every element in the
#array A[i][j] is drawn from the set of integers C = {1, 2, ..., n}, (b) each row is a permutation
#of C, and (c) each column is a permutation of C. In other words, the Miller array is filled
#using n sets of n integers in such a way that no row or column contains the same integer
#twice.
